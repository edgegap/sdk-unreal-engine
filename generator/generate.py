def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)


def main():
    global PREFIX, SERVICE_ENUM, CATEGORY
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--service", choices=SERVICES, default="matchmaker")
    parser.add_argument("--spec", required=True, action="append", help="URL or path; repeat to merge (api v1 + v2)")
    parser.add_argument("--out", required=True, help="the plugin's Source folder: .../Plugin/EdgegapSDK/Source")
    args = parser.parse_args()

    service = SERVICES[args.service]
    PREFIX, SERVICE_ENUM, CATEGORY = service["prefix"], service["enum"], service["category"]

    loaded = [load_spec(s) for s in args.spec]
    spec = merge_specs([s for s, _ in loaded]) if len(loaded) > 1 else loaded[0][0]
    banner = HEADER.format(source=" + ".join(label for _, label in loaded))

    model = Model(spec)
    ops, profiles = collect_operations(model, use_operation_ids=args.service == "api")
    outputs = {
        "Models": emit_models(model, banner),
        "JsonLibrary": emit_json_library(model, banner),
        "Api": emit_api(ops, banner),
        "Nodes": emit_nodes(ops, banner),
    }
    if service["profiles"]:
        outputs["Profiles"] = emit_profiles(model, profiles, banner)
    for name, (h, cpp) in outputs.items():
        module = os.path.join(args.out, "EdgegapClient" if name == "Profiles" else "EdgegapSDK")
        write(os.path.join(module, "Public", "Generated", f"{PREFIX}{name}.h"), h)
        write(os.path.join(module, "Private", "Generated", f"{PREFIX}{name}.cpp"), cpp)

    print(f"{args.service}: {len(ops)} operations, {len(model.structs)} structs, {len(model.enums)} enums"
          + (f", profiles: {', '.join(profiles) or 'none'}" if service["profiles"] else ""))


if __name__ == "__main__":
    main()
