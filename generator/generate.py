#!/usr/bin/env python3
"""Generate the Unreal API layers of the Edgegap SDK plugin from OpenAPI / Swagger specs.

Services and where their spec comes from:
  matchmaker     each matchmaker serves <url>/swagger/v1/swagger.json. Request bodies are a oneOf
                 with one variant per profile, so the output has typed per-profile structs and
                 Find Match nodes on top of the generic API.
  api            api.edgegap.com/swagger.json (v1) and api.edgegap.com/v2/swagger.json (v2).
  serverbrowser  each server browser serves its own spec, like the matchmaker.

Usage:
  python generate.py --service matchmaker --spec https://om-xxxxxxxxxx.edgegap.net --out <source dir>
  python generate.py --service api --spec https://api.edgegap.com/swagger.json \
                     --spec https://api.edgegap.com/v2/swagger.json --out <source dir>

<source dir> is Plugin/EdgegapSDK/Source. API layers go to the shared EdgegapSDK module; the
matchmaker's Find Match (<profile>) helpers go to the EdgegapClient module (they drive the client
subsystem). Only <Prefix>*.h/.cpp under Public/Generated and Private/Generated are written.
Python 3, standard library only.
"""

