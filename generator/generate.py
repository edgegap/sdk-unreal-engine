# ---------------------------------------------------------------- naming helpers

def ascii_only(text):
    return text.encode("ascii", "ignore").decode("ascii")


def pascal(text):
    parts = re.split(r"[^0-9A-Za-z]+", text)
    out = "".join(p[:1].upper() + p[1:] for p in parts if p)
    out = re.sub(r"^([A-Z]{2,})(?=[A-Z][a-z]|$)", lambda m: m.group(1)[0] + m.group(1)[1:].lower(), out)
    if out and out[0].isdigit():
        out = "N" + out
    return out


def singular(word):
    if word.endswith(("ches", "shes", "xes", "sses")):
        return word[:-2]
    if word.endswith("s") and not word.endswith("ss"):
        return word[:-1]
    return word


def name_from_path(method, path):
    if (method, path) in NAME_OVERRIDES:
        return NAME_OVERRIDES[(method, path)]
    segments = [s for s in path.strip("/").split("/") if s and not re.fullmatch(r"v\d+", s)]
    ends_with_param = bool(segments) and segments[-1].startswith("{")
    words = []
    for s in segments:
        if s.startswith("{"):
            continue
        base, _, action = s.partition(":")
        words.append((base, action))
    names = []
    action_name = ""
    for i, (word, action) in enumerate(words):
        last = i == len(words) - 1
        if not last or ends_with_param or method == "post":
            word = singular(word)
        names.append(pascal(word))
        if action:
            action_name = pascal(action)
    if action_name:
        return action_name + "".join(names)
    verb = ("Get" if ends_with_param else "List") if method == "get" else PATH_VERBS[method]
    return verb + "".join(names)


def name_from_operation_id(op_id, path):
    if op_id in OPID_OVERRIDES:
        return OPID_OVERRIDES[op_id]
    words = [w.lower() for w in re.split(r"[^A-Za-z0-9]+", op_id) if w]
    verb_index = next((i for i, w in enumerate(words) if w in OPID_VERBS), None)
    if verb_index is None:
        return pascal("-".join(words))
    verb = OPID_VERBS[words[verb_index]]
    rest = words[:verb_index] + words[verb_index + 1:]
    # A GET on a collection (path not ending in a parameter) lists.
    if verb == "Get" and not path.rstrip("/").endswith("}"):
        verb = "List"
    return verb + "".join(pascal(w) for w in rest)


def words_of(name):
    return re.sub(r"(?<=[a-z0-9])(?=[A-Z])", " ", name)


def comment(text, indent="\t"):
    text = ascii_only(text or "").replace("\r", "").replace("*/", "* /").strip()
    if not text:
        return ""
    lines = text.split("\n")
    if len(lines) == 1:
        return f"{indent}/** {lines[0]} */\n"
    return f"{indent}/**\n" + "".join(f"{indent} * {l}".rstrip() + "\n" for l in lines) + f"{indent} */\n"


def cpp_string(text):
    return ascii_only(text).replace("\\", "\\\\").replace('"', '\\"')


# ---------------------------------------------------------------- spec loading

def rewrite_refs(node, old, new):
    if isinstance(node, dict):
        return {k: (v.replace(old, new, 1) if k == "$ref" and isinstance(v, str) and v.startswith(old) else rewrite_refs(v, old, new))
                for k, v in node.items()}
    if isinstance(node, list):
        return [rewrite_refs(v, old, new) for v in node]
    return node


def swagger2_to_openapi3(spec):
    """Just enough of Swagger 2.0 -> OpenAPI 3 for this generator."""
    spec = rewrite_refs(spec, "#/definitions/", "#/components/schemas/")
    base = spec.get("basePath", "") or ""
    base = "" if base == "/" else base.rstrip("/")
    out = {"openapi": "3.0.0-from-2.0", "info": spec.get("info", {}),
           "components": {"schemas": spec.get("definitions", {})}, "paths": {}}
    for path, item in spec.get("paths", {}).items():
        shared = item.get("parameters", [])
        new_item = {}
        for method, op in item.items():
            if method not in ("get", "post", "put", "patch", "delete"):
                continue
            new_op = {k: v for k, v in op.items() if k not in ("parameters", "responses")}
            params = []
            for p in shared + op.get("parameters", []):
                if p.get("in") == "body":
                    new_op["requestBody"] = {"content": {"application/json": {"schema": p.get("schema", {})}}}
                elif p.get("in") in ("path", "query", "header"):
                    schema = {k: p[k] for k in ("type", "format", "enum", "items") if k in p}
                    params.append({"name": p["name"], "in": p["in"], "required": p.get("required", False),
                                   "description": p.get("description", ""), "schema": schema})
            new_op["parameters"] = params
            new_op["responses"] = {}
            for code, r in op.get("responses", {}).items():
                new_r = {"description": r.get("description", "")}
                if r.get("schema"):
                    new_r["content"] = {"application/json": {"schema": r["schema"]}}
                new_op["responses"][str(code)] = new_r
            new_item[method] = new_op
        out["paths"][base + path] = new_item
    return out


def load_spec(source):
    if re.match(r"https?://", source):
        url = source.rstrip("/")
        if not url.endswith(".json"):
            url += "/swagger/v1/swagger.json"
        with urllib.request.urlopen(url, timeout=30) as r:
            raw = r.read()
        label = re.sub(r"https?://", "", url)
    else:
        with open(source, "rb") as f:
            raw = f.read()
        label = os.path.basename(source)
    spec = json.loads(raw)
    if str(spec.get("swagger", "")).startswith("2"):
        spec = swagger2_to_openapi3(spec)
    elif not str(spec.get("openapi", "")).startswith("3"):
        sys.exit(f"{source}: expected OpenAPI 3 or Swagger 2")
    title = spec.get("info", {}).get("title", "?")
    return spec, f"{label} ({title}, sha256 {hashlib.sha256(raw).hexdigest()[:12]})"


def merge_specs(specs):
    merged = {"openapi": "3", "info": specs[0].get("info", {}), "components": {"schemas": {}}, "paths": {}}
    for index, spec in enumerate(specs):
        schemas = spec.get("components", {}).get("schemas", {})
        suffix = "V" + str(index + 1)
        for key in list(schemas):
            existing = merged["components"]["schemas"].get(key)
            if existing is not None and json.dumps(existing, sort_keys=True) != json.dumps(schemas[key], sort_keys=True):
                spec = rewrite_refs(spec, f"#/components/schemas/{key}", f"#/components/schemas/{key}{suffix}")
                schemas = spec.get("components", {}).get("schemas", {})
                schemas[key + suffix] = schemas.pop(key)
        merged["components"]["schemas"].update(spec.get("components", {}).get("schemas", {}))
        for path, item in spec.get("paths", {}).items():
            merged["paths"].setdefault(path, {}).update(item)
    return merged


# ---------------------------------------------------------------- type model

class Field:
    def __init__(self, json_name, cpp_name, kind, cpp_type, required, description, const=None):
        self.json_name = json_name
        self.cpp_name = cpp_name
        self.kind = kind            # value | raw | enum | struct | const
        self.cpp_type = cpp_type
        self.required = required
        self.description = description
        self.const = const
        self.is_latency_map = False
        self.default = None         # C++ literal of the spec default, for scalars


class Struct:
    def __init__(self, name, description):
        self.name = name
        self.description = description
        self.fields = []


class Model:
    def __init__(self, spec):
        self.spec = spec
        self.components = spec.get("components", {}).get("schemas", {})
        self.structs = []           # in dependency order
        self.struct_by_name = {}
        self.struct_by_shape = {}
        self.enums = {}             # name -> values
        self.component_structs = {}

    @staticmethod
    def shape(schema):
        if isinstance(schema, dict):
            return {k: Model.shape(v) for k, v in sorted(schema.items()) if k not in ("description", "example", "title")}
        if isinstance(schema, list):
            return [Model.shape(v) for v in schema]
        return schema

    def resolve(self, schema):
        ref = schema.get("$ref") if isinstance(schema, dict) else None
        if ref:
            key = ref.split("/")[-1]
            return key, self.components.get(key, {})
        return None, schema

    def component_by_title(self, title):
        for key, schema in self.components.items():
            if schema.get("title") == title:
                return key
        return None

    def enum_type(self, key, schema):
        name = f"E{PREFIX}{pascal(key)}"
        self.enums.setdefault(name, [str(v) for v in schema["enum"]])
        return name

    def struct_for(self, schema, name_hint, profile):
        shape = json.dumps(self.shape(schema), sort_keys=True)
        if shape in self.struct_by_shape:
            return self.struct_by_shape[shape]
        name = f"F{PREFIX}{name_hint}"
        base, n = name, 2
        while name in self.struct_by_name:
            name, n = f"{base}{n}", n + 1
        struct = Struct(name, schema.get("description", ""))
        self.struct_by_name[name] = struct
        self.struct_by_shape[shape] = name
        required = set(schema.get("required", []))
        used = set()
        for json_name, prop in schema.get("properties", {}).items():
            f = self.field(name_hint, json_name, prop, json_name in required, profile)
            while f.cpp_name in used or f.cpp_name == name[1:]:
                f.cpp_name += "_"
            used.add(f.cpp_name)
            struct.fields.append(f)
        self.structs.append(struct)  # after its children: dependency order
        return name

    def component_struct(self, key):
        if key not in self.component_structs:
            self.component_structs[key] = None  # recursion guard
            self.component_structs[key] = self.struct_for(self.components[key], pascal(key), None)
        return self.component_structs[key]

    def field(self, owner_hint, json_name, prop, required, profile):
        description = prop.get("description", "")
        cpp_name = pascal(json_name) or "Value"
        enum = prop.get("enum")
        if enum and len(enum) == 1 and "$ref" not in prop and isinstance(enum[0], str):
            return Field(json_name, cpp_name, "const", "FString", required, description, const=enum[0])
        hint = self.inline_hint(owner_hint, json_name, prop, profile)
        kind, cpp_type = self.type_of(prop, hint, profile)
        if cpp_type == "bool":
            cpp_name = "b" + cpp_name
        f = Field(json_name, cpp_name, kind, cpp_type, required, description)
        f.default = scalar_default(cpp_type, prop.get("default", self.resolve(prop)[1].get("default")))
        f.is_latency_map = cpp_type == "TMap<FString, double>" and ("latenc" in description.lower() or json_name == "beacons")
        return f

    def inline_hint(self, owner_hint, json_name, prop, profile):
        extra = prop.get("additionalProperties")
        title = prop.get("title") or (prop.get("items") or {}).get("title") or (extra.get("title") if isinstance(extra, dict) else None)
        if profile and json_name == "attributes":
            return pascal(profile) + "Attributes"
        if title and re.fullmatch(r"[A-Za-z0-9_]+", title):
            return pascal(title) + (pascal(profile) if profile else "")
        return owner_hint + pascal(json_name)

    def type_of(self, schema, hint, profile):
        """(kind, C++ type) for a schema."""
        key, schema = self.resolve(schema)
        if key is not None:
            if "enum" in schema and schema.get("type", "string") == "string":
                return "enum", self.enum_type(key, schema)
            if schema.get("properties"):
                return "struct", self.component_struct(key)
            hint = pascal(key)
        if any(k in schema for k in ("oneOf", "anyOf", "allOf")):
            return "raw", "FString"
        t = schema.get("type")
        if t == "string":
            if schema.get("format") == "date-time":
                return "value", "FDateTime"
            # Edgegap matchmaker quirk: latency maps say "string" with numeric bounds; they are numbers.
            if "minimum" in schema or "maximum" in schema:
                return "value", "double"
            return "value", "FString"
        if t == "integer":
            return "value", "int64" if schema.get("format") == "int64" else "int32"
        if t == "number":
            return "value", "double"
        if t == "boolean":
            return "value", "bool"
        if t == "array":
            kind, inner = self.type_of(schema.get("items", {}), hint, profile)
            if kind in ("raw", "enum") or inner.startswith(("TArray", "TMap")):
                return "raw", "FString"
            return "value", f"TArray<{inner}>"
        if t == "object" or "properties" in schema or "additionalProperties" in schema:
            if schema.get("properties"):
                return "struct", self.struct_for(schema, hint, profile)
            extra = schema.get("additionalProperties")
            if isinstance(extra, dict) and extra:
                kind, inner = self.type_of(extra, hint, profile)
                if kind in ("raw", "enum") or inner.startswith(("TArray", "TMap")):
                    return "raw", "FString"
                return "value", f"TMap<FString, {inner}>"
        return "raw", "FString"


def scalar_default(cpp_type, value):
    """C++ literal for a spec default on a scalar field, or None."""
    if value is None:
        return None
    if cpp_type == "bool" and isinstance(value, bool):
        return "true" if value else "false"
    if cpp_type in ("int32", "int64") and isinstance(value, (int, float)) and not isinstance(value, bool):
        return str(int(value))
    if cpp_type == "double" and isinstance(value, (int, float)) and not isinstance(value, bool):
        return repr(float(value))
    if cpp_type == "FString" and isinstance(value, str) and value:
        return f'TEXT("{cpp_string(value)}")'
    return None


# ---------------------------------------------------------------- operations

class Param:
    def __init__(self, json_name, cpp_name, cpp_type, where, required):
        self.json_name = json_name
        self.cpp_name = cpp_name
        self.cpp_type = cpp_type
        self.where = where
        self.required = required


class Operation:
    def __init__(self, name, method, path, summary, params, body_struct, response_struct, profile=None):
        self.name = name
        self.method = method
        self.path = path
        self.summary = summary
        self.params = params
        self.body_struct = body_struct
        self.response_struct = response_struct
        self.profile = profile


def variant_profile(variant):
    prop = variant.get("properties", {}).get("profile", {})
    if prop.get("enum") and len(prop["enum"]) == 1:
        return prop["enum"][0]
    m = re.search(r"\((.+)\)$", variant.get("title", ""))
    return m.group(1) if m else None


def response_struct(model, schema, op_name):
    if "oneOf" in schema:
        variant = model.resolve(schema["oneOf"][0])[1]
        key = model.component_by_title(re.sub(r"\s*\(.*\)$", "", variant.get("title", "")))
        return model.component_struct(key) if key else model.struct_for(variant, op_name + "Response", None)
    kind, cpp_type = model.type_of(schema, op_name + "Response", None)
    return cpp_type if kind == "struct" else None


def collect_operations(model, use_operation_ids):
    ops, profiles, names = [], {}, set()
    for path, methods in model.spec.get("paths", {}).items():
        for method, op in methods.items():
            if method not in ("get", "post", "put", "patch", "delete"):
                continue
            op_id = op.get("operationId")
            if op_id in SKIPPED_OPERATION_IDS:
                continue
            name = name_from_operation_id(op_id, path) if use_operation_ids and op_id else name_from_path(method, path)
            if name in names:
                tag = pascal((op.get("tags") or [""])[0])
                name = name + tag if tag and name + tag not in names else name
            base, n = name, 2
            while name in names:
                name, n = f"{base}{n}", n + 1
            names.add(name)

            params, used = [], set()
            for p in op.get("parameters", []):
                if p["in"] == "header" and p["name"].lower() in SKIPPED_HEADERS:
                    continue
                kind, cpp_type = model.type_of(p.get("schema", {}), name + pascal(p["name"]), None)
                if kind != "value" or cpp_type not in ("FString", "int32", "int64", "double", "bool"):
                    cpp_type = "FString"
                cpp_name = pascal(p["name"]) or "Param"
                if cpp_type == "bool":
                    cpp_name = "b" + cpp_name
                while cpp_name in used or cpp_name == "Body":
                    cpp_name += "_"
                used.add(cpp_name)
                params.append(Param(p["name"], cpp_name, cpp_type, p["in"], p.get("required", p["in"] == "path")))

            response = None
            for code, r in sorted(op.get("responses", {}).items()):
                if code.startswith("2"):
                    schema = r.get("content", {}).get("application/json", {}).get("schema")
                    if schema:
                        response = response_struct(model, schema, name)
                    break

            body = op.get("requestBody", {}).get("content", {}).get("application/json", {}).get("schema")
            summary = op.get("summary") or op.get("description", "")
            if body is None:
                ops.append(Operation(name, method, path, summary, params, None, response))
                continue
            if "oneOf" in body:
                variants = body["oneOf"]
                base_title = re.sub(r"\s*\(.*\)$", "", model.resolve(variants[0])[1].get("title", name + "Request"))
                generic_key = model.component_by_title(base_title)
                if generic_key:
                    ops.append(Operation(name, method, path, summary, params, model.component_struct(generic_key), response))
                for variant in variants:
                    variant = model.resolve(variant)[1]
                    profile = variant_profile(variant)
                    if not profile:
                        continue
                    struct = model.struct_for(variant, pascal(generic_key or base_title) + pascal(profile), profile)
                    ops.append(Operation(name + pascal(profile), method, path, summary, params, struct, response, profile))
                    attrs = next((f for f in model.struct_by_name[struct].fields if f.json_name == "attributes" and f.kind == "struct"), None)
                    if attrs and path in ("/groups", "/tickets"):
                        profiles.setdefault(profile, attrs.cpp_type)
            else:
                kind, struct = model.type_of(body, name + "Request", None)
                ops.append(Operation(name, method, path, summary, params, struct if kind == "struct" else None, response))
    return ops, profiles


# ---------------------------------------------------------------- emitters

def enum_members(values):
    members, used = [], {"Unknown"}
    for v in values:
        m = pascal(v.lower()) or "Empty"
        if m == "Unknown":
            members.append(None)  # already the fallback
            continue
        base, n = m, 2
        while m in used:
            m, n = f"{base}{n}", n + 1
        used.add(m)
        members.append(m)
    return members


def short_name(cpp_type):
    return cpp_type[len("F" + PREFIX):]


def emit_models(model, banner):
    h = [banner, "#pragma once\n\n", '#include "CoreMinimal.h"\n', '#include "EdgegapJson.h"\n',
         f'#include "{PREFIX}Models.generated.h"\n\n']
    cpp = [banner, f'#include "Generated/{PREFIX}Models.h"\n\n']

    for name, values in model.enums.items():
        members = enum_members(values)
        short = name[len("E" + PREFIX):]
        h.append(f"UENUM(BlueprintType)\nenum class {name} : uint8\n{{\n\tUnknown,\n")
        for v, m in zip(values, members):
            if m:
                h.append(f'\t{m} UMETA(DisplayName = "{cpp_string(v)}"),\n')
        h.append("};\n\n")
        h.append(f"{API} {name} {PREFIX}Parse{short}(const FString& Value);\n")
        h.append(f"{API} FString {PREFIX}ToString({name} Value);\n\n")
        cpp.append(f"{name} {PREFIX}Parse{short}(const FString& Value)\n{{\n")
        for v, m in zip(values, members):
            if m:
                cpp.append(f'\tif (Value == TEXT("{cpp_string(v)}")) {{ return {name}::{m}; }}\n')
        cpp.append(f"\treturn {name}::Unknown;\n}}\n\n")
        cpp.append(f"FString {PREFIX}ToString({name} Value)\n{{\n\tswitch (Value)\n\t{{\n")
        for v, m in zip(values, members):
            if m:
                cpp.append(f'\tcase {name}::{m}: return TEXT("{cpp_string(v)}");\n')
        cpp.append("\tdefault: return FString();\n\t}\n}\n\n")

    for s in model.structs:
        h.append(comment(s.description, ""))
        h.append(f"USTRUCT(BlueprintType)\nstruct {API} {s.name}\n{{\n\tGENERATED_BODY()\n\n")
        for f in s.fields:
            if f.kind == "const":
                h.append(f'\t/** Always "{cpp_string(f.const)}" for this type. */\n')
                h.append(f'\tstatic const TCHAR* Fixed{f.cpp_name}() {{ return TEXT("{cpp_string(f.const)}"); }}\n\n')
                continue
            desc = f.description
            if f.kind == "raw":
                desc = (desc + "\n" if desc else "") + "JSON text (the spec leaves this field untyped)."
            if f.is_latency_map:
                desc += "\nLeave empty when finding a match: the subsystem measures beacon latencies."
            h.append(comment(desc))
            h.append(f'\tUPROPERTY(EditAnywhere, BlueprintReadWrite, Category = "{CATEGORY}")\n')
            default = {"bool": " = false", "int32": " = 0", "int64": " = 0", "double": " = 0.0"}.get(f.cpp_type, "")
            if f.default is not None:
                default = f" = {f.default}"
            if f.kind == "enum":
                default = f" = {f.cpp_type}::Unknown"
            h.append(f"\t{f.cpp_type} {f.cpp_name}{default};\n\n")
            if f.kind == "struct" and not f.required:
                h.append(f'\t/** True when {cpp_string(f.json_name)} is present. */\n')
                h.append(f'\tUPROPERTY(EditAnywhere, BlueprintReadWrite, Category = "{CATEGORY}")\n')
                h.append(f"\tbool bHas{f.cpp_name} = false;\n\n")
        h.append("\tvoid ReadJson(const FJsonObject& Obj);\n\tTSharedRef<FJsonObject> WriteJson() const;\n};\n\n")

        cpp.append(f"void {s.name}::ReadJson(const FJsonObject& Obj)\n{{\n")
        if not any(f.kind != "const" for f in s.fields):
            cpp.append("\t(void)Obj;\n")
        for f in s.fields:
            j = cpp_string(f.json_name)
            if f.kind == "const":
                continue
            if f.kind == "raw":
                cpp.append(f'\tEdgegapJson::ReadRaw(Obj, TEXT("{j}"), {f.cpp_name});\n')
            elif f.kind == "enum":
                short = f.cpp_type[len("E" + PREFIX):]
                cpp.append(f'\t{{ FString S; if (EdgegapJson::FromValue(Obj.TryGetField(TEXT("{j}")), S)) {{ {f.cpp_name} = {PREFIX}Parse{short}(S); }} }}\n')
            elif f.kind == "struct" and not f.required:
                cpp.append(f'\tbHas{f.cpp_name} = EdgegapJson::FromValue(Obj.TryGetField(TEXT("{j}")), {f.cpp_name});\n')
            else:
                cpp.append(f'\tEdgegapJson::Read(Obj, TEXT("{j}"), {f.cpp_name});\n')
        cpp.append("}\n\n")

        cpp.append(f"TSharedRef<FJsonObject> {s.name}::WriteJson() const\n{{\n\tTSharedRef<FJsonObject> Obj = MakeShared<FJsonObject>();\n")
        for f in s.fields:
            j = cpp_string(f.json_name)
            if f.kind == "const":
                cpp.append(f'\tObj->SetStringField(TEXT("{j}"), Fixed{f.cpp_name}());\n')
                continue
            guard = ""
            if not f.required:
                if f.kind == "struct":
                    guard = f"if (bHas{f.cpp_name}) "
                elif f.cpp_type == "FString" or f.cpp_type.startswith(("TArray", "TMap")):
                    guard = f"if (!{f.cpp_name}.IsEmpty()) "
                elif f.kind == "enum":
                    guard = f"if ({f.cpp_name} != {f.cpp_type}::Unknown) "
                elif f.default is not None and f.cpp_type != "FString":
                    guard = f"if ({f.cpp_name} != {f.default}) "
                elif f.cpp_type == "bool":
                    guard = f"if ({f.cpp_name}) "
                elif f.cpp_type in ("int32", "int64", "double"):
                    guard = f"if ({f.cpp_name} != 0) "
                elif f.cpp_type == "FDateTime":
                    guard = f"if ({f.cpp_name} != FDateTime()) "
            if f.kind == "raw":
                cpp.append(f'\t{guard}EdgegapJson::WriteRaw(*Obj, TEXT("{j}"), {f.cpp_name});\n')
            elif f.kind == "enum":
                cpp.append(f'\t{guard}Obj->SetStringField(TEXT("{j}"), {PREFIX}ToString({f.cpp_name}));\n')
            else:
                cpp.append(f'\t{guard}EdgegapJson::Write(*Obj, TEXT("{j}"), {f.cpp_name});\n')
        cpp.append("\treturn Obj;\n}\n\n")
    return "".join(h), "".join(cpp)


def emit_json_library(model, banner):
    """Blueprint To/From JSON string conversions for every generated struct."""
    h = [banner, "#pragma once\n\n", '#include "CoreMinimal.h"\n', '#include "Kismet/BlueprintFunctionLibrary.h"\n',
         f'#include "Generated/{PREFIX}Models.h"\n', f'#include "{PREFIX}JsonLibrary.generated.h"\n\n',
         f"UCLASS()\nclass {API} U{PREFIX}JsonLibrary : public UBlueprintFunctionLibrary\n{{\n\tGENERATED_BODY()\n\npublic:\n"]
    cpp = [banner, f'#include "Generated/{PREFIX}JsonLibrary.h"\n\n']
    for s in model.structs:
        short = short_name(s.name)
        h.append(f'\tUFUNCTION(BlueprintPure, Category = "{CATEGORY}|JSON", meta = (DisplayName = "To JSON String ({short})", CompactNodeTitle = "->", BlueprintAutocast))\n')
        h.append(f"\tstatic FString Conv_{short}ToString(const {s.name}& Value);\n\n")
        h.append(f'\tUFUNCTION(BlueprintCallable, Category = "{CATEGORY}|JSON", meta = (DisplayName = "From JSON String ({short})"))\n')
        h.append(f"\tstatic bool {short}FromJson(const FString& Json, {s.name}& Value);\n\n")
        cpp.append(f"FString U{PREFIX}JsonLibrary::Conv_{short}ToString(const {s.name}& Value)\n{{\n\treturn EdgegapJson::ObjectToString(Value.WriteJson());\n}}\n\n")
        cpp.append(f"bool U{PREFIX}JsonLibrary::{short}FromJson(const FString& Json, {s.name}& Value)\n{{\n")
        cpp.append("\tconst TSharedPtr<FJsonObject> Obj = EdgegapJson::ParseObject(Json);\n\tif (!Obj.IsValid()) { return false; }\n")
        cpp.append("\tValue.ReadJson(*Obj);\n\treturn true;\n}\n\n")
    h.append("};\n")
    return "".join(h), "".join(cpp)


def op_args(op):
    args = []
    for p in op.params:
        args.append(f"const {p.cpp_type}& {p.cpp_name}" if p.cpp_type == "FString" else f"{p.cpp_type} {p.cpp_name}")
    if op.body_struct:
        args.append(f"const {op.body_struct}& Body")
    return args


def callback_type(op):
    if op.response_struct:
        return f"TFunction<void(const {op.response_struct}&, const FEdgegapError&)>"
    return "TFunction<void(const FEdgegapError&)>"


def op_doc(op):
    doc = f"{op.method.upper()} {op.path}" + (f": {op.summary}" if op.summary else "")
    if op.profile:
        doc += f' (profile "{op.profile}", typed attributes)'
    return doc


def emit_api(ops, banner):
    h = [banner, "#pragma once\n\n", '#include "CoreMinimal.h"\n', '#include "EdgegapCore.h"\n',
         f'#include "Generated/{PREFIX}Models.h"\n\n',
         "/** C++ API: one static function per operation. Callbacks run on the game thread. */\n",
         f"class {API} F{PREFIX}Api\n{{\npublic:\n"]
    cpp = [banner, f'#include "Generated/{PREFIX}Api.h"\n', '#include "GenericPlatform/GenericPlatformHttp.h"\n\n']
    for op in ops:
        args = op_args(op) + [f"{callback_type(op)} Done"]
        h.append(comment(op_doc(op)))
        h.append(f"\tstatic void {op.name}({', '.join(args)});\n\n")

        cpp.append(f"void F{PREFIX}Api::{op.name}({', '.join(args)})\n{{\n")
        cpp.append("\tauto OnResponse = [Done](const FEdgegapResponse& R)\n\t{\n")
        if op.response_struct:
            cpp.append(f"\t\t{op.response_struct} Out;\n")
            cpp.append("\t\tif (!R.Error.bFailed)\n\t\t{\n\t\t\tif (const TSharedPtr<FJsonObject> Obj = EdgegapJson::ParseObject(R.Body)) { Out.ReadJson(*Obj); }\n\t\t}\n")
            cpp.append("\t\tDone(Out, R.Error);\n")
        else:
            cpp.append("\t\tDone(R.Error);\n")
        cpp.append("\t};\n")
        for p in op.params:
            if (p.where == "path" or p.required) and p.cpp_type == "FString":
                cpp.append(f'\tif ({p.cpp_name}.IsEmpty()) {{ FEdgegapHttp::FailLater(TEXT("{op.name}: {p.cpp_name} is empty."), OnResponse); return; }}\n')

        pieces = []
        for seg in op.path.strip("/").split("/"):
            parts = re.split(r"(\{[^}]+\})", seg)
            expr = []
            for part in parts:
                if not part:
                    continue
                m = re.fullmatch(r"\{(.+)\}", part)
                if m:
                    p = next(p for p in op.params if p.json_name == m.group(1))
                    value = p.cpp_name if p.cpp_type == "FString" else f"LexToString({p.cpp_name})"
                    expr.append(f"FGenericPlatformHttp::UrlEncode({value})")
                else:
                    expr.append(f'TEXT("{part}")')
            pieces.append('TEXT("/") + ' + " + ".join(expr))
        cpp.append(f"\tFString Path = FString() + {' + '.join(pieces)};\n")

        query = [p for p in op.params if p.where == "query"]
        if query:
            cpp.append("\tTArray<FString> QueryParts;\n")
            for p in query:
                key = f'FString(TEXT("{p.json_name}="))'
                if p.cpp_type == "FString":
                    cpp.append(f"\tif (!{p.cpp_name}.IsEmpty()) {{ QueryParts.Add({key} + FGenericPlatformHttp::UrlEncode({p.cpp_name})); }}\n")
                elif p.cpp_type == "bool":
                    cpp.append(f'\tQueryParts.Add({key} + ({p.cpp_name} ? TEXT("true") : TEXT("false")));\n')
                else:
                    cpp.append(f"\tif ({p.cpp_name} > 0) {{ QueryParts.Add({key} + LexToString({p.cpp_name})); }}\n")
            cpp.append('\tif (QueryParts.Num() > 0) { Path += TEXT("?") + FString::Join(QueryParts, TEXT("&")); }\n')

        cpp.append("\tTMap<FString, FString> Headers;\n")
        for p in op.params:
            if p.where == "header":
                value = p.cpp_name if p.cpp_type == "FString" else f"LexToString({p.cpp_name})"
                cpp.append(f'\tif (!{value}.IsEmpty()) {{ Headers.Add(TEXT("{"Authorization" if p.json_name.lower() == "authorization" else p.json_name}"), {value}); }}\n')
        body = "EdgegapJson::ObjectToString(Body.WriteJson())" if op.body_struct else "FString()"
        cpp.append(f'\tFEdgegapHttp::Send(EEdgegapService::{SERVICE_ENUM}, TEXT("{op.method.upper()}"), Path, {body}, Headers, OnResponse);\n}}\n\n')
    h.append("};\n")
    return "".join(h), "".join(cpp)


def emit_nodes(ops, banner):
    h = [banner, "#pragma once\n\n", '#include "CoreMinimal.h"\n', '#include "Kismet/BlueprintAsyncActionBase.h"\n',
         f'#include "Generated/{PREFIX}Api.h"\n', f'#include "{PREFIX}Nodes.generated.h"\n\n']
    cpp = [banner, f'#include "Generated/{PREFIX}Nodes.h"\n\n']
    delegates = {}
    for op in ops:
        if op.response_struct and op.response_struct not in delegates:
            d = f"F{PREFIX}On{short_name(op.response_struct)}"
            delegates[op.response_struct] = d
            h.append(f"DECLARE_DYNAMIC_MULTICAST_DELEGATE_TwoParams({d}, const {op.response_struct}&, Response, const FEdgegapError&, Error);\n")
    h.append("\n")
    for op in ops:
        cls = f"U{PREFIX}Node_{op.name}"
        delegate = delegates.get(op.response_struct, "FEdgegapOnDone")
        display = words_of(op.name[: -len(pascal(op.profile))] if op.profile else op.name)
        if op.profile:
            display += f" ({cpp_string(op.profile)})"
        args = op_args(op)
        members = [(p.cpp_name, p.cpp_type) for p in op.params] + ([("Body", op.body_struct)] if op.body_struct else [])
        h.append(f"UCLASS()\nclass {API} {cls} : public UBlueprintAsyncActionBase\n{{\n\tGENERATED_BODY()\n\npublic:\n")
        h.append(comment(op_doc(op)))
        h.append(f'\tUFUNCTION(BlueprintCallable, meta = (BlueprintInternalUseOnly = "true", DisplayName = "{display}"), Category = "{CATEGORY}")\n')
        h.append(f"\tstatic {cls}* {op.name}({', '.join(args)});\n\n")
        h.append(f"\tUPROPERTY(BlueprintAssignable)\n\t{delegate} OnSuccess;\n\n")
        h.append(f"\tUPROPERTY(BlueprintAssignable)\n\t{delegate} OnFailure;\n\n")
        h.append("\tvirtual void Activate() override;\n\nprivate:\n")
        for n, t in members:
            h.append(f"\t{t} {n}{' = 0' if t in ('int32', 'int64') else ' = 0.0' if t == 'double' else ' = false' if t == 'bool' else ''};\n")
        h.append("};\n\n")

        cpp.append(f"{cls}* {cls}::{op.name}({', '.join(args)})\n{{\n\t{cls}* Node = NewObject<{cls}>();\n")
        for n, _ in members:
            cpp.append(f"\tNode->{n} = {n};\n")
        cpp.append("\treturn Node;\n}\n\n")
        call_args = ", ".join(n for n, _ in members)
        if op.response_struct:
            lam = f"[this](const {op.response_struct}& Response, const FEdgegapError& Error)"
            fire = "(Error.bFailed ? OnFailure : OnSuccess).Broadcast(Response, Error);"
        else:
            lam = "[this](const FEdgegapError& Error)"
            fire = "(Error.bFailed ? OnFailure : OnSuccess).Broadcast(Error);"
        sep = ", " if call_args else ""
        cpp.append(f"void {cls}::Activate()\n{{\n\tAddToRoot();\n")
        cpp.append(f"\tF{PREFIX}Api::{op.name}({call_args}{sep}{lam}\n\t{{\n\t\t{fire}\n\t\tRemoveFromRoot();\n\t\tSetReadyToDestroy();\n\t}});\n}}\n\n")
    return "".join(h), "".join(cpp)


def emit_profiles(model, profiles, banner):
    h = [banner, "#pragma once\n\n", '#include "CoreMinimal.h"\n', '#include "Kismet/BlueprintFunctionLibrary.h"\n',
         f'#include "Generated/{PREFIX}Models.h"\n', f'#include "{PREFIX}Profiles.generated.h"\n\n',
         "/** One Find Match function per matchmaker profile, with that profile's typed attributes. */\n",
         f"UCLASS()\nclass EDGEGAPCLIENT_API U{PREFIX}Profiles : public UBlueprintFunctionLibrary\n{{\n\tGENERATED_BODY()\n\npublic:\n",
         "\t/** Profiles defined in the matchmaker configuration this code was generated from. */\n",
         f'\tUFUNCTION(BlueprintPure, Category = "{CATEGORY}")\n\tstatic TArray<FString> GetProfileNames();\n\n']
    cpp = [banner, f'#include "Generated/{PREFIX}Profiles.h"\n', '#include "EdgegapMatchmakerSubsystem.h"\n',
           '#include "Engine/Engine.h"\n', '#include "Engine/GameInstance.h"\n', '#include "Engine/World.h"\n\n',
           f"TArray<FString> U{PREFIX}Profiles::GetProfileNames()\n{{\n\tTArray<FString> Names;\n" +
           "".join(f'\tNames.Add(TEXT("{cpp_string(p)}"));\n' for p in profiles) + "\treturn Names;\n}\n\n"]
    for profile, attrs in profiles.items():
        fn = f"FindMatch{pascal(profile)}"
        latency = [f.json_name for f in model.struct_by_name[attrs].fields if f.is_latency_map]
        h.append(f'\t/** Search for a match with profile "{cpp_string(profile)}". Progress and results come from the Edgegap Matchmaker subsystem. */\n')
        h.append(f'\tUFUNCTION(BlueprintCallable, meta = (WorldContext = "WorldContextObject", DisplayName = "Find Match ({cpp_string(profile)})"), Category = "{CATEGORY}")\n')
        h.append(f"\tstatic void {fn}(const UObject* WorldContextObject, const {attrs}& Attributes);\n\n")
        cpp.append(f"void U{PREFIX}Profiles::{fn}(const UObject* WorldContextObject, const {attrs}& Attributes)\n{{\n")
        cpp.append("\tUWorld* World = GEngine ? GEngine->GetWorldFromContextObject(WorldContextObject, EGetWorldErrorMode::LogAndReturnNull) : nullptr;\n")
        cpp.append("\tUEdgegapMatchmakerSubsystem* Subsystem = World && World->GetGameInstance() ? World->GetGameInstance()->GetSubsystem<UEdgegapMatchmakerSubsystem>() : nullptr;\n")
        cpp.append("\tif (Subsystem)\n\t{\n\t\tTArray<FString> LatencyAttributes;\n")
        cpp.append("".join(f'\t\tLatencyAttributes.Add(TEXT("{l}"));\n' for l in latency))
        cpp.append(f'\t\tSubsystem->FindMatch(TEXT("{cpp_string(profile)}"), EdgegapJson::ObjectToString(Attributes.WriteJson()), LatencyAttributes);\n\t}}\n}}\n\n')
    h.append("};\n")
    return "".join(h), "".join(cpp)


